#area of triangle and rectangle
#take values for triangle
base = int(input("Enter base:"))
height = int(input("Enter height:"))

#perfrom operation 
triangle = 0.5 * base * height # area =1/2 *b *h

#take values for rectangle
length = int(input("Enter length:"))
breath = int(input("Enter breath:"))

#perfrom operation
rectangle = length * breath

#display result
print("Area of triangle=", triangle)
print("Area of rectangle=",rectangle)
